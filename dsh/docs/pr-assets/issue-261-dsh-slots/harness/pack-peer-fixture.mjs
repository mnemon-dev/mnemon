import assert from 'node:assert/strict';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
const args = new Map();
for (let i = 2; i < process.argv.length; i += 2) args.set(process.argv[i], process.argv[i + 1]);
const source = resolve(args.get('--source') ?? join(dirname(fileURLToPath(import.meta.url)), 'e2e/peer-fixture'));
const output = resolve(args.get('--output') ?? join(dirname(fileURLToPath(import.meta.url)), 'e2e/artifacts/peer-fixture'));
await mkdir(output, { recursive: true });
const manifest = JSON.parse(await readFile(join(source, 'package.json'), 'utf8'));
const result = spawnSync('npm', ['pack', '--ignore-scripts', '--json', '--pack-destination', output], { cwd: source, encoding: 'utf8' });
assert.equal(result.status, 0, result.stderr);
const [packed] = JSON.parse(result.stdout);
const bytes = await readFile(join(output, packed.filename));
assert.equal(packed.integrity, 'sha512-' + createHash('sha512').update(bytes).digest('base64'));
const artifact = { name: manifest.name, version: manifest.version, filename: packed.filename, integrity: packed.integrity, shasum: packed.shasum, sha256: createHash('sha256').update(bytes).digest('hex'), manifest, source, provenance: 'Test-owned client plugin, loaded through the official DSH bundle/client loader.' };
await writeFile(join(output, 'artifact.json'), JSON.stringify(artifact, null, 2) + '\n');
console.log(join(output, 'artifact.json'));
